const messages: Record<InterfaceLanguage, Record<TranslationKey, string>> = { zh, en }

export interface TranslationParams {
  [key: string]: string | number
}

export function translate(language: InterfaceLanguage, key: TranslationKey, params?: TranslationParams): string {
  const template = messages[language][key]
  if (!params) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = params[name]
    return value === undefined ? match : String(value)
  })
}

export interface TranslationContext {
  language: InterfaceLanguage
  t: (key: TranslationKey, params?: TranslationParams) => string
}

export function useTranslation(): TranslationContext {
  const language = useAtomValue(settingsPreferencesAtom).interfaceLanguage
  const t = React.useCallback(
    (key: TranslationKey, params?: TranslationParams) => translate(language, key, params),
    [language],
  )
  return { language, t }
}

export type { TranslationKey }
