/**
 * browser-use native host 安装（macOS/Linux；Windows 二期）。
 *
 * 与 claudeInChrome/setup.ts 同款两件套：wrapper 脚本（manifest 的 path 不能带
 * 参数，所以落一个 sh 脚本 exec 本 CLI 的 --browser-native-host 模式）+ 各浏览器
 * NativeMessagingHosts manifest。幂等：内容一致则跳过写入。
 */
import { existsSync } from 'fs'
import { chmod, mkdir, readFile, writeFile } from 'fs/promises'
import { join } from 'path'
import { isInBundledMode } from '../bundledMode.js'
import { getAllNativeMessagingHostsDirs } from '../claudeInChrome/common.js'
import { logForDebugging } from '../debug.js'
import { distRoot } from '../distRoot.js'
import { getClaudeConfigHomeDir } from '../envUtils.js'
import { getPlatform } from '../platform.js'

// 注意：Chrome native messaging host 名只允许 [a-z0-9._]，不能带连字符
export const BROWSER_NATIVE_HOST_NAME = 'com.claudecodebest.browser'
/** manifest key 固定的扩展 ID（packages/browser-use/extension/src/manifest.json）。 */
export const BROWSER_EXTENSION_ID = 'gbdgipjmibglhghpmhfflcmiogahjagd'

const BROWSER_HOST_MANIFEST_NAME = `${BROWSER_NATIVE_HOST_NAME}.json`

function browserUseDir(): string {
  return join(getClaudeConfigHomeDir(), 'browser-use')
}

/** wrapper 脚本路径（与 host socket 同目录：~/.claude/browser-use/）。 */
export function getBrowserNativeHostWrapperPath(): string {
  return join(browserUseDir(), 'browser-native-host')
}

async function createWrapperScript(): Promise<string> {
  const wrapperPath = getBrowserNativeHostWrapperPath()
  // bundled 产物本身就是 CLI 二进制；dev/dist 运行时需要显式指到 cli.js。
  // distRoot 语义随运行位置变化（src 运行→项目根，dist 运行→dist/），
  // 两个候选位做存在性探测，必须指向真实构建产物（feature 门在构建/注入时决定）。
  const cliPath = [
    join(distRoot, 'cli.js'),
    join(distRoot, 'dist', 'cli.js'),
  ].find(existsSync)
  const command = isInBundledMode()
    ? `"${process.execPath}" --browser-native-host`
    : cliPath
      ? `"${process.execPath}" "${cliPath}" --browser-native-host`
      : `echo "browser native host: cli.js not built (run: bun run build)" >&2; exit 1`
  const scriptContent = `#!/bin/sh
# CCB browser-use native host wrapper script
# Generated by Claude Code - do not edit manually
exec ${command}
`

  const existing = await readFile(wrapperPath, 'utf-8').catch(() => null)
  if (existing === scriptContent) return wrapperPath

  await mkdir(browserUseDir(), { recursive: true })
  await writeFile(wrapperPath, scriptContent)
  await chmod(wrapperPath, 0o755)
  logForDebugging(`[browser-use] Installed native host wrapper: ${wrapperPath}`)
  return wrapperPath
}

/**
 * 幂等安装 native host：wrapper 脚本 + 各浏览器 NativeMessagingHosts manifest。
 * 写不进的目录（浏览器未装/权限）逐个跳过，整体不抛错——调用方是
 * fire-and-forget，安装失败只影响浏览器侧连不上（EXTENSION_OFFLINE）。
 */
export async function ensureBrowserNativeHostInstalled(): Promise<void> {
  if (getPlatform() === 'windows') return

  try {
    const wrapperPath = await createWrapperScript()
    const manifest = {
      name: BROWSER_NATIVE_HOST_NAME,
      description: 'CCB Browser Use Native Host',
      path: wrapperPath,
      type: 'stdio',
      allowed_origins: [`chrome-extension://${BROWSER_EXTENSION_ID}/`],
    }
    const manifestContent = JSON.stringify(manifest, null, 2)

    for (const { path: hostsDir } of getAllNativeMessagingHostsDirs()) {
      const manifestPath = join(hostsDir, BROWSER_HOST_MANIFEST_NAME)
      const existing = await readFile(manifestPath, 'utf-8').catch(() => null)
      if (existing === manifestContent) continue
      try {
        await mkdir(hostsDir, { recursive: true })
        await writeFile(manifestPath, manifestContent)
        logForDebugging(
          `[browser-use] Installed native host manifest at: ${manifestPath}`,
        )
      } catch (error) {
        logForDebugging(
          `[browser-use] Failed to install manifest at ${manifestPath}: ${error}`,
        )
      }
    }
  } catch (error) {
    logForDebugging(`[browser-use] Native host install failed: ${error}`)
  }
}
